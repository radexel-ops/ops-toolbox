/**
 * Create an icon element
 * @param {string} name - Icon name from Icons object
 * @param {object} options - Configuration options
 * @param {string} options.size - Icon size (default: 18)
 * @param {string} options.class - Additional CSS classes
 * @param {string} options.ariaLabel - Accessibility label
 * @returns {HTMLElement} SVG icon element
 */
function createIcon(name, options = {}) {
    const { size = 18, className = '', ariaLabel = '' } = options;

    const iconSvg = Icons[name];
    if (!iconSvg) {
        console.warn(`Icon "${name}" not found`);
        return document.createElement('span');
    }

    const wrapper = document.createElement('span');
    wrapper.className = `icon ${className}`.trim();
    wrapper.innerHTML = iconSvg;

    const svg = wrapper.querySelector('svg');
    if (svg) {
        svg.setAttribute('width', size);
        svg.setAttribute('height', size);
        svg.setAttribute('aria-hidden', ariaLabel ? 'false' : 'true');
        if (ariaLabel) {
            svg.setAttribute('aria-label', ariaLabel);
            svg.setAttribute('role', 'img');
        }
    }

    return wrapper;
}

/**
 * Get raw SVG string for an icon
 * @param {string} name - Icon name
 * @param {number} size - Icon size
 * @returns {string} SVG HTML string
 */
function getIconSvg(name, size = 18) {
    const iconSvg = Icons[name];
    if (!iconSvg) {
        return '';
    }
    return iconSvg.replace('<svg', `<svg width="${size}" height="${size}"`);
}

/**
 * Replace all emoji icons with SVG icons
 * Scans for elements with data-icon attribute and replaces content
 */
function replaceEmojiIcons() {
    const emojiMap = {
        '📊': 'layout-dashboard',
        '💬': 'message-square',
        '🤖': 'bot',
        '📚': 'library',
        '⚙️': 'settings',
        '🛠️': 'shield',
        '📋': 'file-edit',
        '🚪': 'log-out',
    };

    // Replace in nav-icon elements
    document.querySelectorAll('.nav-icon').forEach(el => {
        const emoji = el.textContent.trim();
        const iconName = emojiMap[emoji];
        if (iconName) {
            el.innerHTML = getIconSvg(iconName, 18);
            el.classList.add('svg-icon');
        }
    });

    // Replace in dropdown items
    document.querySelectorAll('.dropdown-item > span:first-child').forEach(el => {
        const emoji = el.textContent.trim();
        const iconName = emojiMap[emoji];
        if (iconName) {
            el.innerHTML = getIconSvg(iconName, 16);
            el.classList.add('svg-icon');
        }
    });
}

